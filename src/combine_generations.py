"""Merge the models' generations (four in Part I; three in Part II via configs/combine_generations_p2.json) into ONE side-by-side Markdown file.

What it does
------------
Reads results/generations_<model>.json for the n-gram, RNN, LSTM and Transformer
(each written by src/generate.py), checks that all four used IDENTICAL decoding
settings, the same prompts and the same number of samples, and writes
results/part1_generations.md: the shared settings at the top, then one section
per prompt with the four models' texts under it, so they can be read side by
side. It adds no commentary; it only rearranges what generate.py saved.

If the models' decoding settings differ in any way (temperature, top-k, tokens,
seed, banned tokens, stop rule, number of samples) or their prompts differ, it
stops with an error instead of writing a file that would compare unlike things.

Run:   python3 src/combine_generations.py --config configs/combine_generations.json
"""

import argparse
import json

from runconfig import add_config_args, load_config, save_run

LABELS = {"ngram": "N-gram (trigram, Kneser-Ney)", "rnn": "RNN", "lstm": "LSTM", "transformer": "Transformer"}


def escape(text):
    """Stop Markdown from treating words like '*' or '<br>' as formatting."""
    for ch in "\\`*_{}[]<>#|":
        text = text.replace(ch, "\\" + ch)
    return text


def load_runs(opts):
    runs = {}
    for model in opts["models"]:
        path = opts["input_template"].format(model=model)
        try:
            with open(path) as f:
                runs[model] = json.load(f)
        except FileNotFoundError:
            raise SystemExit(f"{path} not found: generate from '{model}' first "
                             f"(python3 src/generate.py --config configs/generations_{model}.json).")
    return runs


def check_identical(runs):
    """All models must share decoding settings, prompts file and prompt list."""
    models = list(runs)
    first = runs[models[0]]
    for m in models[1:]:
        if runs[m]["decoding"] != first["decoding"]:
            raise SystemExit(f"Decoding settings of '{m}' differ from '{models[0]}':\n"
                             f"  {runs[m]['decoding']}\n  {first['decoding']}")
        mine = [(g["prompt"], g["sample"]) for g in runs[m]["generations"]]
        theirs = [(g["prompt"], g["sample"]) for g in first["generations"]]
        if mine != theirs:
            raise SystemExit(f"'{m}' was generated for different prompts/samples than '{models[0]}'.")


def build_markdown(runs, opts):
    labels = {**LABELS, **opts.get("labels", {})}  # optional per-config labels (Part II uses them)
    models = list(runs)
    decoding = runs[models[0]]["decoding"]
    lines = ["# " + opts.get("title", "Part I generations: all models, identical decoding"), "",
             "Generated by `src/combine_generations.py` from the per-model files in `results/`. "
             "No editing or commentary. The text after each prompt is the generated continuation.", "",
             "## Decoding settings (identical for every model)", "",
             "| Setting | Value |", "|---|---|"]
    for key, value in decoding.items():
        lines.append(f"| {key} | {escape(json.dumps(value))} |")
    lines.append(f"| prompts file | `{runs[models[0]]['details']['prompts_path']}` |")
    lines += ["", "## Where each model's text came from", "",
              "| Model | Source file | Git commit | Hardware | Date |", "|---|---|---|---|---|"]
    for m in models:
        r = runs[m]
        lines.append(f"| {labels.get(m, m)} | `{opts['input_template'].format(model=m)}` | `{r['git_commit'][:7]}` | "
                     f"{escape(r['hardware'])} | {r['date']} |")

    by_model = {m: {(g["prompt"], g["sample"]): g for g in runs[m]["generations"]} for m in models}
    keys = [(g["prompt"], g["sample"]) for g in runs[models[0]]["generations"]]
    prompts = list(dict.fromkeys(p for p, _ in keys))  # unique, in file order
    num_samples = decoding["num_samples"]
    for number, prompt in enumerate(prompts, 1):
        lines += ["", f"## Prompt {number}: {escape(prompt)}"]
        for sample in range(num_samples):
            if num_samples > 1:
                lines += ["", f"### Sample {sample}"]
            for m in models:
                g = by_model[m][(prompt, sample)]
                end = f" ⟨eos after {g['num_new_tokens']} tokens⟩" if g["ended_with_eos"] else f" ⟨{g['num_new_tokens']} tokens, no eos⟩"
                lines += ["", f"**{labels.get(m, m)}**", "",
                          f"> {escape(' '.join(g['prompt_tokens']))} **{escape(g['continuation'])}**{end}"]
    return "\n".join(lines) + "\n", len(prompts), len(keys)


def main():
    parser = argparse.ArgumentParser(description="Combine per-model generations into one Markdown file.")
    add_config_args(parser)
    args = parser.parse_args()
    config, run = load_config(args)
    opts = config["options"]
    runs = load_runs(opts)
    check_identical(runs)
    text, num_prompts, num_generations_per_model = build_markdown(runs, opts)
    with open(opts["output_path"], "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Wrote {opts['output_path']}: {num_prompts} prompts x {len(runs)} models")
    save_run(args.results_dir, run, "src/combine_generations.py", config,
             metrics={"num_prompts": num_prompts, "num_models": len(runs),
                      "generations_per_model": num_generations_per_model},
             details={"output_path": opts["output_path"], "decoding": runs[opts["models"][0]]["decoding"],
                      "sources": {m: {"git_commit": r["git_commit"], "hardware": r["hardware"], "date": r["date"]}
                                  for m, r in runs.items()}})


if __name__ == "__main__":
    main()
